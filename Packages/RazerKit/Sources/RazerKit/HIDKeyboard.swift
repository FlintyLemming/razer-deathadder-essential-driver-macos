        0x4A: 0x7F, 0x4B: 0x54, 0x4C: 0x58, 0x4E: 0x56, 0x4F: 0x6D, 0x50: 0x6E, 0x51: 0x67,
        0x52: 0x62, 0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C, 0x57: 0x5D, 0x58: 0x5E,
