        0x69: 0x68, 0x6A: 0x6B, 0x6B: 0x69, 0x6D: 0x43, 0x6E: 0x65, 0x6F: 0x45, 0x71: 0x6A,
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x76: 0x3D, 0x77: 0x4D, 0x78: 0x3B,
        0x79: 0x4E, 0x7A: 0x3A, 0x7B: 0x50, 0x7C: 0x4F, 0x7D: 0x51, 0x7E: 0x52,
    ]
}
